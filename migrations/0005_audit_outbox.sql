-- 0005_audit_outbox — transactional outbox of this service's audit records (0.2.0).
--
-- Until 0.2.0 the service published its own security events (sign-ins,
-- password, MFA, session, API key, membership and organization changes) with
-- the kit's best-effort AuditService.record: during a NATS outage they were
-- dropped and only counted in aisits_audit_failures_total. They are now
-- written to this table in the transaction of the change they describe
-- (AuditService.enqueue): a rolled-back change leaves no record, a committed
-- one keeps its record until the kit's OutboxRelay has published it on
-- audit.v1.auth (the auth-audit consumer then stores it in audit_logs like
-- every other service's record).
--
-- The kit's outboxTableSql() of @darmawanweb/ais-its-nest 0.3.0, verbatim
-- (per-key mode: every replica relays; audit records carry no entity key,
-- so they are unordered). Published rows are deleted after the relay's
-- retention; rows that can never be published are parked (failed_at).

CREATE TABLE IF NOT EXISTS "outbox" (
  id uuid PRIMARY KEY,
  seq bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
  type text NOT NULL,
  entity_key text,
  data jsonb NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  attempts integer NOT NULL DEFAULT 0,
  next_attempt_at timestamptz,
  last_error text,
  published_at timestamptz,
  failed_at timestamptz
);
CREATE INDEX IF NOT EXISTS "outbox_pending_idx" ON "outbox" (created_at, id)
  WHERE published_at IS NULL AND failed_at IS NULL;
CREATE INDEX IF NOT EXISTS "outbox_pending_seq_idx" ON "outbox" (seq)
  WHERE published_at IS NULL AND failed_at IS NULL;
CREATE INDEX IF NOT EXISTS "outbox_pending_key_idx" ON "outbox" (entity_key, seq)
  WHERE published_at IS NULL AND failed_at IS NULL;
CREATE INDEX IF NOT EXISTS "outbox_retry_idx" ON "outbox" (entity_key, seq)
  WHERE published_at IS NULL AND failed_at IS NULL AND next_attempt_at IS NOT NULL;
CREATE INDEX IF NOT EXISTS "outbox_failed_idx" ON "outbox" (failed_at)
  WHERE failed_at IS NOT NULL;
